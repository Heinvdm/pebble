def normalise(text: str, own_name: str = "pebble") -> str:
    out = (text or "").lower()
    out = out.replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"').replace("…", " ")
    out = out.replace("-", " ")
    for pattern, replacement in _CONTRACTIONS:
        out = pattern.sub(replacement, out)
    out = PUNCT.sub(" ", out)
    out = re.sub(rf"\b{re.escape(own_name.lower())}\b", " ", out)
    out = re.sub(r"\s+([,?!.])", r"\1", out)
    out = re.sub(r"([,?!.])(?=\S)", r"\1 ", out)
    out = SPACES.sub(" ", out).strip()
    out = re.sub(r"^[,.!?\s]+", "", out)
    out = re.sub(r"(,\s*)+", ", ", out)
    return out.strip(" ,")


def number(text: str) -> float | None:
    text = text.strip()
    try:
        return float(text)
    except ValueError:
        return NUMBERS.get(text)
